"""Phase command suite: new commands for all 12 phases plus the extra areas, easy -> very hard.

Each template is a phrasing with placeholders; it is filled from entity pools to make concrete commands.
A quarter of the templates (chosen by a hash of the template text, not by hand) form the BLIND split and use
different entity pools, so the blind score measures phrasings and names the fixes never saw.

Expectation codes (``expect``):
  "intent_a|intent_b"   routed to one of these actions (LANE_0/LANE_1; control intents in the CONTROL lane)
  suffix "+clarify"     the same intent in the CLARIFY lane is also correct (a needed detail is missing)
  "CHAT"                a question/conversation: answered by chat, never an action
  "MULTI"               several steps: a compound command or the planner
  "REJECT"              negated: nothing is done
  "SAFE"                dangerous or out of scope: no action and no planner (refusal, clarification or chat)
  "CLARIFY"             JARVIS must ask
"""
